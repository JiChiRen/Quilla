/**
 * \file
 * Clock cross-checking: measure the LSI against a system-clock time base.
 *
 * WHY THIS EXISTS
 * ---------------
 * The independent watchdog is clocked from the LSI, an RC oscillator that
 * this part does not characterise in any document available to the project.
 * dev/qwdt.h therefore carries the LSI rate as an explicit engineering
 * assumption (24 / 32 / 60 kHz) and says so. That assumption is the widest
 * single input to the watchdog's timeout bounds: at the slow end it stretches
 * the 500 ms target to 666 ms, which is what gets compared against the
 * process safety time, and at the fast end it squeezes it to 266 ms, which
 * is what constrains how often software may feed.
 *
 * This module replaces the assumption with a measurement. It times a fixed
 * number of LSI ticks with a timer that runs from the system clock and
 * reports the rate that falls out. qwdt_calibrate() then feeds that number
 * back into the watchdog so its bounds are computed from the oscillator this
 * board actually has.
 *
 * WHAT IT DETECTS, AND WHAT IT CANNOT
 * -----------------------------------
 * Two oscillators generated by different circuits are compared against each
 * other, so what is observable is their RATIO. That covers the failure modes
 * that matter for a watchdog - one clock drifting, stopping, or being
 * switched to a different source - because those change the ratio.
 *
 * It does NOT measure absolute accuracy. Both clocks here are RC oscillators
 * (the system clock is the HSI; no HSE is fitted in this configuration), so
 * a drift that moved both by the same factor is invisible, and neither rate
 * can be called "correct". Do not present a reading from here as calibration
 * against a reference.
 *
 * It also cannot report a total loss of the system clock: if that clock stops
 * so does the CPU, and nothing is there to observe it. Detecting that needs
 * either a clock security system - this part does not expose one - or an
 * external watchdog, which is a separate line in the diagnostic plan.
 *
 * HOW IT MEASURES
 * ---------------
 * TIM14 runs from the APB clock (system-clock derived) and free-runs; the
 * LPTIM1 counter, already clocked from the LSI by rtimer-arch.c, is read
 * through rtimer_arch_now(). Both are sampled at the ends of a window whose
 * length is fixed in TIM14 counts, so the divisor is a compile-time constant
 * and no 64-bit division is pulled into the image. The module never
 * reconfigures LPTIM1: it only reads it, which keeps rtimer untouched.
 *
 * Because the window is fixed, the running check degenerates to "the number
 * of LSI counts seen inside one window must stay inside a band" - no division
 * at all on the periodic path.
 *
 * TERMINATION OF qclk_calibrate()
 * -------------------------------
 * The calibration loop waits for TIM14 to advance by a fixed number of counts
 * and has no iterative timeout. That is deliberate and bounded: qclk_init()
 * rejects a reference frequency below QCLK_CONF_REF_MIN_HZ, so one window
 * cannot take longer than QCLK_CONF_WINDOW_TICKS / QCLK_CONF_REF_MIN_HZ
 * seconds. The only way the loop does not finish is the system clock stopping,
 * which stops the CPU with it - a state no software loop can report.
 */

#ifndef QCLK_H_
#define QCLK_H_

#include "sys/kern-status.h"

#include <stdint.h>

/**
 * \brief Counting rate aimed for on the reference timer, Hz.
 *
 * The prescaler is chosen so the real rate is at or below this value.
 * 1 MHz keeps one 50,000-count window at 50 ms and keeps the 16-bit counter
 * from wrapping inside it.
 */
#ifndef QCLK_CONF_REF_HZ
#define QCLK_CONF_REF_HZ            1000000UL
#endif

/**
 * \brief Slowest reference rate accepted, Hz.
 *
 * This is what bounds the calibration loop: a slower reference would stretch
 * the blocking window and there would be no way to tell a slow clock from a
 * stalled one.
 */
#ifndef QCLK_CONF_REF_MIN_HZ
#define QCLK_CONF_REF_MIN_HZ        100000UL
#endif

/** Fastest reference rate accepted, Hz. */
#ifndef QCLK_CONF_REF_MAX_HZ
#define QCLK_CONF_REF_MAX_HZ        48000000UL
#endif

/**
 * \brief Length of one measurement window, in reference counts.
 *
 * Larger means finer resolution and a longer blocking calibration. At the
 * default 1 MHz reference this is 50 ms, which resolves the LSI to about
 * 0.06% - far below any tolerance the oscillator needs.
 */
#ifndef QCLK_CONF_WINDOW_TICKS
#define QCLK_CONF_WINDOW_TICKS      50000UL
#endif

/**
 * \brief Rate assumed before the first measurement completes, Hz.
 *
 * Only used to sanity-check the first window and to seed the comparison band
 * if qclk_calibrate() is never called.
 */
#ifndef QCLK_CONF_LSI_NOMINAL_HZ
#define QCLK_CONF_LSI_NOMINAL_HZ    32000UL
#endif

/** Slowest LSI rate the measurement accepts, Hz. Outside means fault. */
#ifndef QCLK_CONF_LSI_MIN_HZ
#define QCLK_CONF_LSI_MIN_HZ        8000UL
#endif

/** Fastest LSI rate the measurement accepts, Hz. Outside means fault. */
#ifndef QCLK_CONF_LSI_MAX_HZ
#define QCLK_CONF_LSI_MAX_HZ        128000UL
#endif

/**
 * \brief Half-width of the running comparison band, parts per thousand.
 *
 * Applied to the measured rate in both directions. This has to cover the
 * drift the oscillator shows across the product's temperature and life, not
 * the accuracy of the measurement, which is two orders of magnitude finer.
 * It is an assumption, and is reported as one.
 */
#ifndef QCLK_CONF_TOLERANCE_PPT
#define QCLK_CONF_TOLERANCE_PPT     100UL
#endif

/**
 * \brief Reader for the clock under test.
 *
 * Must return a monotonically increasing count of LSI ticks, wide enough not
 * to wrap inside one window. The default reads LPTIM1 as started by
 * rtimer-arch.c, which limits this module to images that include the rtimer
 * (the APP image; QBOOT does not start LPTIM1).
 */
#ifndef QCLK_CONF_READ_TICKS
#define QCLK_CONF_READ_TICKS()      ((uint32_t)rtimer_arch_now())
#endif

/** Clock cross-check is always enabled; the "clk" shell command was removed.
 *  QCLK_CONF_SHELL is retained for compatibility. */
#ifndef QCLK_CONF_SHELL
#define QCLK_CONF_SHELL             1
#endif

/**
 * \brief          Start the reference timer and reject an unusable rate
 * \retval KERN_OK         reference running, ready to measure
 * \retval KERN_ERR_RANGE  the APB clock cannot produce a reference rate
 *                         inside [QCLK_CONF_REF_MIN_HZ, QCLK_CONF_REF_MAX_HZ]
 *
 * Does not start the clock under test: that is owned by rtimer-arch.c and is
 * already running by the time anything calls this.
 */
kern_status_t qclk_init(void);

/**
 * \brief          Measure the LSI rate once, blocking
 * \retval KERN_OK         measured_hz updated
 * \retval KERN_ERR_NOT_READY qclk_init() has not run
 * \retval KERN_ERR_RANGE  the result fell outside
 *                         [QCLK_CONF_LSI_MIN_HZ, QCLK_CONF_LSI_MAX_HZ]
 *
 * Takes one window (QCLK_CONF_WINDOW_TICKS reference counts, 50 ms at the
 * defaults). Call it before qwdt_init() so the watchdog can be calibrated
 * from the measurement instead of from the assumed rate.
 */
kern_status_t qclk_calibrate(void);

/**
 * \brief          Compare the clock under test against the measured band
 * \retval KERN_OK         window not finished yet, or finished inside the band
 * \retval KERN_ERR_CLOCK  a completed window fell outside the band
 * \retval KERN_ERR_NOT_READY qclk_init() has not run
 *
 * Intended for the idle loop. It arms a window on the first call, then does
 * nothing but read the reference counter until that window closes; only then
 * is one comparison made. A violation is raised through kern_raise() with
 * KERN_MOD_CLOCK before this returns.
 */
kern_status_t qclk_poll(void);

/** \brief Rate measured by the last completed window, Hz. 0 if none yet. */
unsigned long qclk_measured_lsi_hz(void);

/** \brief Counting rate the reference timer actually runs at, Hz. 0 if idle. */
unsigned long qclk_reference_hz(void);

/** \brief Number of completed windows since start-up. */
unsigned int qclk_window_count(void);

/** \brief Number of windows that fell outside the band. */
unsigned int qclk_violation_count(void);

/** \brief Rate seen in the most recent window, Hz, band or not. */
unsigned long qclk_last_window_hz(void);

/**
 * \brief          Describe the current state into a caller's buffer
 * \param dst      Destination buffer, NUL terminated on success
 * \param len      Capacity of dst in bytes
 * \return         Bytes written excluding the terminator, 0 if not ready
 *
 * Kept free of printf so that no image is forced to link a formatter.
 */
unsigned int qclk_describe(char *dst, unsigned int len);


#endif /* QCLK_H_ */
